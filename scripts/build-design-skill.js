// Generates the two derived files in the internal `luxe-design` skill from
// `src/luxe-tokens.css`, which stays the single source of truth for every value
// in the system.
//
//   node scripts/build-design-skill.js          # write the files
//   node scripts/build-design-skill.js --check  # fail (exit 1) if they are stale
//
// What is generated and why:
//
//   .agents/skills/luxe-design/tokens.css
//     A verbatim copy of the `:root` block. The skill has to hand agents a
//     drop-in stylesheet, and the skill directory is not served by any route,
//     so it cannot `@import` the product's copy. Copying is the only option;
//     generating the copy is what stops it drifting.
//
//   .agents/skills/luxe-design/adherence.json
//     The machine-readable half of the design rules: the token inventory plus
//     the families, sizes, weights and radii the adherence lint enforces.
//     Upstream shipped a 14 KB hand-maintained manifest beside a 155 KB
//     generated bundle whose generator was not in the repository. The bundle is
//     deleted (decision D9); the manifest is kept but derived, because the lint
//     is a real consumer and a hand-maintained list of tokens is a list that
//     goes stale.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const TOKENS_SOURCE = new URL("../src/luxe-tokens.css", import.meta.url);
const SKILL_DIR = new URL("../.agents/skills/luxe-design/", import.meta.url);
const TOKENS_TARGET = new URL("tokens.css", SKILL_DIR);
const ADHERENCE_TARGET = new URL("adherence.json", SKILL_DIR);

const GENERATED_BY = "scripts/build-design-skill.js";

/** @typedef {{ name: string, value: string, kind: string, group: string }} Token */

/**
 * Classifies a token by its value, not by its name: a rename must not silently
 * change what the lint thinks a token is.
 * @param {string} value
 * @returns {string}
 */
function kindOf(value) {
  if (/^#[0-9a-f]{3,8}$/i.test(value) || /^rgba?\(/i.test(value)) return "color";
  // px, plus the relative units. --tracking-brand is em because a wordmark's tracking
  // should scale with its size, unlike the px tracking on the fixed content scale.
  if (/^-?\d+(\.\d+)?(px|em|rem)$/.test(value)) return "length";
  if (/^\d+ms$/.test(value)) return "duration";
  if (/^cubic-bezier\(/.test(value)) return "easing";
  if (/(^|,)\s*("|-apple-system|ui-monospace)/.test(value)) return "font-family";
  if (/^\d+(\.\d+)?$/.test(value)) return "number";
  if (/rgba?\(/i.test(value)) return "shadow";
  return "other";
}

/**
 * @param {string} css
 * @returns {Token[]}
 */
function parseTokens(css) {
  /** @type {Token[]} */
  const tokens = [];
  let group = "ungrouped";
  for (const line of css.split("\n")) {
    const declaration = /^\s*(--[a-z0-9-]+)\s*:\s*([^;]+);/i.exec(line);
    if (!declaration) {
      // Section headings look like `/* ---- Type (spec 2.1) ---------- */`.
      const heading = /\/\*\s*-{3,}\s*(.+?)\s*-{3,}/.exec(line);
      if (heading) group = heading[1];
      continue;
    }
    const [, name, value] = declaration;
    tokens.push({ name, value: value.trim(), kind: kindOf(value.trim()), group });
  }
  return tokens;
}

/**
 * The first quoted family in a font stack is the bundled face; the rest of the
 * stack is the fallback chain and is not a family the system offers.
 * @param {Token[]} tokens
 * @param {string} name
 * @returns {string}
 */
function bundledFamily(tokens, name) {
  const token = tokens.find((entry) => entry.name === name);
  if (!token) throw new Error(`${name} is missing from luxe-tokens.css`);
  const quoted = /"([^"]+)"/.exec(token.value);
  if (!quoted) throw new Error(`${name} does not start with a quoted family`);
  return quoted[1];
}

/**
 * @param {Token[]} tokens
 * @param {RegExp} pattern
 * @returns {Record<string, string>}
 */
function subset(tokens, pattern) {
  return Object.fromEntries(
    tokens.filter((token) => pattern.test(token.name)).map((token) => [token.name, token.value]),
  );
}

/**
 * @param {string} css
 * @returns {string}
 */
function renderTokensCss(css) {
  const rootAt = css.indexOf(":root {");
  if (rootAt === -1) throw new Error("luxe-tokens.css no longer opens a :root block");
  return [
    `/* GENERATED by ${GENERATED_BY} from src/luxe-tokens.css. Do not edit.`,
    " *",
    " * The Luxe design tokens, verbatim. Every value in this skill resolves",
    " * through these custom properties; this file is the only place in the skill",
    " * where a literal colour, size or radius may appear.",
    " *",
    ' * Drop-in use: `@import "tokens.css";` then build with the variables.',
    " */",
    css.slice(rootAt),
  ].join("\n");
}

/**
 * @param {Token[]} tokens
 * @returns {string}
 */
function renderAdherenceJson(tokens) {
  const manifest = {
    generatedBy: GENERATED_BY,
    source: "src/luxe-tokens.css",
    note: "Derived file. Run `npm run build:design-skill` after changing the tokens.",
    families: {
      sans: bundledFamily(tokens, "--font-sans"),
      mono: bundledFamily(tokens, "--font-mono"),
      // Scoped to the wordmark. Listed here so the lint knows the face exists at all;
      // "only on the wordmark" is a rule the token comment states and review enforces,
      // not something a regex over CSS declarations can check.
      brand: bundledFamily(tokens, "--font-brand"),
    },
    fontSizes: subset(tokens, /^--text-/),
    fontWeights: subset(tokens, /^--weight-/),
    radii: subset(tokens, /^--radius-/),
    rules: [
      {
        id: "no-literal-color",
        message: "Raw colour literal. Use a token via var(), or add the value to src/luxe-tokens.css.",
      },
      {
        id: "font-family",
        message:
          "Font not provided by the design system. Two content families, the sans and the mono above, plus the brand face on the wordmark only.",
      },
      {
        id: "font-size",
        message: "Font size outside the scale. Four content sizes plus the brand size, all listed in fontSizes.",
      },
      {
        id: "font-weight",
        message: "Font weight outside the scale. Two weights only: regular and medium. No bold, no light.",
      },
      {
        id: "border-radius",
        message: "Radius outside the geometry scale. Use a var(--radius-*) token.",
      },
    ],
    tokens,
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

const css = await readFile(TOKENS_SOURCE, "utf8");
const tokens = parseTokens(css);
if (tokens.length === 0) throw new Error("no tokens parsed out of luxe-tokens.css");

/** @type {[URL, string][]} */
const outputs = [
  [TOKENS_TARGET, renderTokensCss(css)],
  [ADHERENCE_TARGET, renderAdherenceJson(tokens)],
];

if (process.argv.includes("--check")) {
  for (const [target, expected] of outputs) {
    let actual = null;
    try {
      actual = await readFile(target, "utf8");
    } catch {
      // missing file falls through to the mismatch branch below
    }
    if (actual !== expected) {
      console.error(`${fileURLToPath(target)} is out of date. Run \`node ${GENERATED_BY}\` and commit the result.`);
      process.exit(1);
    }
  }
  console.log(`Design skill derived files are up to date (${tokens.length} tokens).`);
} else {
  for (const [target, expected] of outputs) {
    await writeFile(target, expected);
    console.log(`Wrote ${fileURLToPath(target)}`);
  }
}
